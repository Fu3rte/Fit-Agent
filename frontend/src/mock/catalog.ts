/**
 * 3.1 已拍可推荐最小标准：动作身份与来源已核对、动作处于 active、器械／记录／负重口径
 * 与动作模式完整。通过者才进入候选；生成时再按正式档案器械、具体动作限制与动作模式
 * 限制过滤（F2-02）。不读后端 `recommendable`（stage1 保持全 0，未经检查）。
 */
export function isRecommendableCandidate(e: CatalogExercise): boolean {
  if (!e.active) return false;
  // 身份与来源已核对（核不上的条目不导入）
  if (!e.id || !e.standard_name_zh || !e.source_ref) return false;
  // 器械、记录类型、负重口径与动作模式完整；负重口径只属于负重次数型，其余必须为 null
  if (!e.equipment_variant || e.modes.length === 0) return false;
  if (e.record_type === "reps_weight") return e.load_convention !== null;
  return e.load_convention === null;
}
